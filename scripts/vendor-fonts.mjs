// Vendors every font file the design asks for, exactly as Google Fonts serves
// them to a modern browser, keeping font-weight and unicode-range, and records
// a SHA-256 per file in assets/fonts/manifest.json. Stops loudly on a partial set.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'assets', 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const REQUESTS = [
  'https://fonts.googleapis.com/css2?family=Outfit:wght@100..900&display=swap',
  'https://fonts.googleapis.com/css2?family=Roboto+Flex:opsz,wght@8..144,100..1000&display=swap',
  'https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@100..800&display=swap',
  'https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200&display=block'
];

fs.mkdirSync(outDir, { recursive: true });
const manifest = { generated: new Date().toISOString(), requests: REQUESTS, files: [] };
let css = '/* Generated by scripts/vendor-fonts.mjs. Do not edit by hand. */\n';

for (const url of REQUESTS) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Font CSS request failed: ${url} -> HTTP ${res.status}`);
  let text = await res.text();
  const urls = [...text.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]);
  if (!urls.length) throw new Error(`No font files in ${url}`);
  const family = (url.match(/family=([^:&]+)/)?.[1] || 'font').toLowerCase().replace(/[^a-z0-9]+/g, '');
  let n = 0;
  for (const fileUrl of urls) {
    // Short names: Windows checkouts fail on very long paths.
    const name = `${family}-${++n}.woff2`;
    const r = await fetch(fileUrl, { headers: { 'User-Agent': UA } });
    if (!r.ok) throw new Error(`Font file failed: ${fileUrl} -> HTTP ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length < 1000) throw new Error(`Font file suspiciously small: ${fileUrl}`);
    fs.writeFileSync(path.join(outDir, name), buf);
    manifest.files.push({ name, source: fileUrl, bytes: buf.length, sha256: crypto.createHash('sha256').update(buf).digest('hex') });
    text = text.replace(fileUrl, `./${name}`);
  }
  css += text + '\n';
}
fs.writeFileSync(path.join(outDir, 'fonts.css'), css);
fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2));
console.log(`Vendored ${manifest.files.length} font files.`);
