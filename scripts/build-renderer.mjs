// Bundles the renderer with esbuild, copies HTML, CSS and vendored fonts, and
// generates the offline docs bundle from every Markdown article under docs/.
// Fails the build if any article in docs/ is missing from the bundle.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';
import { parseChangelog } from './lib/changelog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
fs.mkdirSync(path.join(dist, 'styles'), { recursive: true });

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith('.md') ? [path.join(d, e.name)] : []));
const docsDir = path.join(root, 'docs');
const files = fs.existsSync(docsDir) ? walk(docsDir).sort() : [];
const articles = files.map((f) => {
  const body = fs.readFileSync(f, 'utf8');
  const rel = path.relative(root, f).replace(/\\/g, '/');
  const title = (body.match(/^#\s+(.+)$/m) || [, path.basename(f, '.md')])[1].trim();
  const parts = rel.split('/');
  const category = parts.length > 3 ? parts[2].replace(/-/g, ' ').replace(/^\w/, (c) => c.toUpperCase()) : 'General';
  return { path: rel, title, category, body };
});
const missing = files.filter((f) => !articles.some((a) => a.path === path.relative(root, f).replace(/\\/g, '/')));
if (missing.length) { console.error('Docs missing from bundle:', missing); process.exit(1); }

const changelogSrc = fs.existsSync(path.join(root, 'CHANGELOG.md')) ? fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8') : '';
const changelog = parseChangelog(changelogSrc, process.env);
fs.writeFileSync(path.join(root, 'src/renderer/docs-bundle.js'), `// Generated by scripts/build-renderer.mjs\nexport const ARTICLES = ${JSON.stringify(articles)};\nexport const CHANGELOG = ${JSON.stringify(changelog)};\n`);

if (!process.env.MT_SKIP_APP_BUNDLE) await esbuild.build({
  entryPoints: [path.join(root, 'src/renderer/app.js')],
  bundle: true, format: 'iife', platform: 'browser', target: 'chrome130',
  outfile: path.join(dist, 'app.js'), sourcemap: false, minify: !!process.env.MT_MINIFY,
  external: ['node:crypto'], logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' }
});
fs.copyFileSync(path.join(root, 'src/renderer/index.html'), path.join(dist, 'index.html'));
for (const css of ['tokens.css', 'app.css', 'mesh2.css']) fs.copyFileSync(path.join(root, 'src/renderer/styles', css), path.join(dist, 'styles', css));
fs.cpSync(path.join(root, 'assets/fonts'), path.join(dist, 'fonts'), { recursive: true });
console.log(`Renderer built. ${articles.length} articles, ${changelog.length} changelog entries.`);
